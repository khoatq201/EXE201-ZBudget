class AppSpacing {
  // Base spacing unit
  static const double base = 8.0;

  // Spacing scale
  static const double xs = base * 0.5; // 4
  static const double sm = base * 1; // 8
  static const double md = base * 1.5; // 12
  static const double lg = base * 2; // 16
  static const double xl = base * 3; // 24
  static const double xl2 = base * 4; // 32
  static const double xl3 = base * 5; // 40
  static const double xl4 = base * 6; // 48
  static const double xl5 = base * 8; // 64
  static const double xl6 = base * 10; // 80

  // Specific spacing values
  static const double pagePadding = lg; // 16
  static const double cardPadding = md; // 12
  static const double buttonPadding = sm; // 8
  static const double inputPadding = md; // 12
  static const double sectionSpacing = xl; // 24
  static const double itemSpacing = md; // 12
  static const double iconSpacing = sm; // 8
}
