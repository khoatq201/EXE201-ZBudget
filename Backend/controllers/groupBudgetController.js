/**
 * @desc    Join group budget by invite code
 * @route   POST /api/group-budgets/join
 * @access  Private
 */
export const joinGroupBudget = async (req, res) => {
  const userId = req.userId;
  const { inviteCode, contributionPercentage } = req.body;

  try {
    if (!inviteCode) {
      throw new BadRequestError('Invite code là bắt buộc');
    }

    // Find budget by invite code
    const groupBudget = await GroupBudget.findOne({ inviteCode: inviteCode.toUpperCase() });
    if (!groupBudget) {
      throw new NotFoundError('Không tìm thấy GroupBudget với mã này');
    }

    if (!groupBudget.isActive) {
      throw new BadRequestError('GroupBudget này không còn hoạt động');
    }

    // Get user info
    const user = await User.findById(userId).select('profile.name email');
    if (!user) {
      throw new NotFoundError('Không tìm thấy user');
    }

    const userName = user.profile?.name || user.email || 'Unknown';

    // Add member to budget
    groupBudget.addMember(userId, userName, contributionPercentage || 0);
    await groupBudget.save();

    successResponse(res, 'Tham gia GroupBudget thành công', groupBudget, 200);
  } catch (error) {
    console.error('❌ Join GroupBudget error:', error);
    if (error instanceof BadRequestError || error instanceof NotFoundError) {
      throw error;
    }
    throw new BadRequestError(error.message);
  }
};

/**
 * @desc    Invite user to group budget by email or userId
 * @route   POST /api/group-budgets/:id/invite
 * @access  Private
 */
export const inviteToGroupBudget = async (req, res) => {
  const userId = req.userId;
  const { id } = req.params;
  const { email, inviteUserId, contributionPercentage } = req.body;

  try {
    const groupBudget = await GroupBudget.findById(id);
    if (!groupBudget) {
      throw new NotFoundError('Không tìm thấy GroupBudget');
    }

    // Check if requester is member
    const isMember = groupBudget.members.some(m => m.userId.toString() === userId.toString());
    if (!isMember) {
      throw new ForbiddenError('Bạn không phải thành viên của budget này');
    }

    // Find user to invite
    let invitedUser;
    if (inviteUserId) {
      invitedUser = await User.findById(inviteUserId).select('profile.name email');
    } else if (email) {
      invitedUser = await User.findOne({ email }).select('profile.name email');
    } else {
      throw new BadRequestError('Cần provide email hoặc userId');
    }

    if (!invitedUser) {
      throw new NotFoundError('Không tìm thấy user để invite');
    }

    const userName = invitedUser.profile?.name || invitedUser.email || 'Unknown';

    // Add member
    groupBudget.addMember(invitedUser._id, userName, contributionPercentage || 0);
    await groupBudget.save();

    successResponse(res, 'Invite thành công', {
      groupBudget,
      invitedUser: {
        _id: invitedUser._id,
        name: userName,
        email: invitedUser.email,
      }
    }, 200);
  } catch (error) {
    console.error('❌ Invite to GroupBudget error:', error);
    if (error instanceof BadRequestError || error instanceof NotFoundError || error instanceof ForbiddenError) {
      throw error;
    }
    throw new BadRequestError(error.message);
  }
};

/**
 * @desc    Update group budget
 * @route   PUT /api/group-budgets/:id
 * @access  Private
 */
export const updateGroupBudget = async (req, res) => {
  const userId = req.userId;
  const { id } = req.params;
  const updates = req.body;

  try {
    const groupBudget = await GroupBudget.findById(id);
    if (!groupBudget) {
      throw new NotFoundError('Không tìm thấy GroupBudget');
    }

    // Only creator or members can update
    const isMember = groupBudget.members.some(m => m.userId.toString() === userId.toString());
    const isCreator = groupBudget.createdBy.toString() === userId.toString();

    if (!isMember && !isCreator) {
      throw new ForbiddenError('Bạn không có quyền cập nhật budget này');
    }

    // Allowed fields to update
    const allowedUpdates = ['name', 'description', 'totalBudget', 'endDate', 'autoSplitByContribution', 'allowPartialTag'];
    Object.keys(updates).forEach(key => {
      if (allowedUpdates.includes(key)) {
        groupBudget[key] = updates[key];
      }
    });

    await groupBudget.save();

    successResponse(res, 'Cập nhật GroupBudget thành công', groupBudget);
  } catch (error) {
    console.error('❌ Update GroupBudget error:', error);
    if (error instanceof NotFoundError || error instanceof ForbiddenError) {
      throw error;
    }
    throw new BadRequestError(error.message);
  }
};

