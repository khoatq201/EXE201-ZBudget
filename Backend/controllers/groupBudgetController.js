/**
 * @desc    Create new group budget (independent, no Group required)
 * @route   POST /api/group-budgets
 * @access  Private
 */
export const createGroupBudget = async (req, res) => {
  const userId = req.userId;
  const { name, description, totalBudget, currency, startDate, endDate, members, autoSplitByContribution, allowPartialTag } = req.body;

  try {
    // Validate members
    if (!members || members.length === 0) {
      throw new BadRequestError('Phải có ít nhất 1 thành viên');
    }

    // Validate total percentage = 100
    const totalPercentage = members.reduce((sum, m) => sum + m.contributionPercentage, 0);
    if (Math.abs(totalPercentage - 100) > 0.01) {
      throw new BadRequestError(`Tổng phần trăm đóng góp phải bằng 100%. Hiện tại: ${totalPercentage}%`);
    }

    // Get member names from User collection
    const memberIds = members.map(m => m.userId);
    const users = await User.find({ _id: { $in: memberIds } }).select('profile.name email');

    const membersWithNames = members.map(m => {
      const user = users.find(u => u._id.toString() === m.userId.toString());
      return {
        userId: m.userId,
        name: m.name || user?.profile?.name || user?.email || 'Unknown',
        contributionPercentage: m.contributionPercentage,
      };
    });

    // Create group budget (invite code will be auto-generated by pre-save)
    const groupBudget = new GroupBudget({
      createdBy: userId,
      name,
      description,
      totalBudget,
      currency: currency || 'VND',
      startDate: startDate || new Date(),
      endDate,
      members: membersWithNames,
      autoSplitByContribution: autoSplitByContribution !== undefined ? autoSplitByContribution : true,
      allowPartialTag: allowPartialTag !== undefined ? allowPartialTag : true,
    });

    await groupBudget.save();

    successResponse(res, 'Tạo GroupBudget thành công', groupBudget, 201);
  } catch (error) {
    console.error('❌ Create GroupBudget error:', error);
    if (error instanceof BadRequestError || error instanceof NotFoundError) {
      throw error;
    }
    throw new BadRequestError(error.message);
  }
};

/**
 * @desc    Get all group budgets for current user
 * @route   GET /api/group-budgets
 * @access  Private
 */
export const getGroupBudgets = async (req, res) => {
  const userId = req.userId;
  const { isActive, isSettled } = req.query;

  try {
    const filter = {
      'members.userId': userId,
    };

    if (isActive !== undefined) {
      filter.isActive = isActive === 'true';
    }
    if (isSettled !== undefined) {
      filter.isSettled = isSettled === 'true';
    }

    const budgets = await GroupBudget.find(filter)
      .populate('createdBy', 'profile.name email')
      .populate('members.userId', 'profile.name email')
      .sort({ createdAt: -1 });

    successResponse(res, 'Lấy danh sách GroupBudget thành công', budgets);
  } catch (error) {
    console.error('❌ Get GroupBudgets error:', error);
    throw new BadRequestError(error.message);
  }
};

