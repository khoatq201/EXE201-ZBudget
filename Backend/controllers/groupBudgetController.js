/**
 * @desc    Add expense to group budget
 * @route   POST /api/group-budgets/:id/expenses
 * @access  Private
 */
export const addExpenseToGroupBudget = async (req, res) => {
  const userId = req.userId;
  const { id } = req.params;
  const { description, amount, category, date, splitType, participantUserIds, customSplits, location, notes, receiptUrl } = req.body;

  try {
    const groupBudget = await GroupBudget.findById(id);
    if (!groupBudget) {
      throw new NotFoundError('Không tìm thấy GroupBudget');
    }

    // Check if user is member
    const member = groupBudget.members.find(m => m.userId.toString() === userId.toString());
    if (!member) {
      throw new ForbiddenError('Bạn không phải thành viên của budget này');
    }

    // Estimate user's share for personal expense record
    const estimatedShare = splitType === 'equal'
      ? amount / groupBudget.members.length
      : amount * (member.contributionPercentage / 100);

    // Option B: Create personal Expense record first
    const personalExpense = new Expense({
      userId,
      title: `${description} (${groupBudget.name})`,
      description: `Group expense from ${groupBudget.name}`,
      amount,
      category: category || 'other',
      date: date || new Date(),
      groupBudgetId: groupBudget._id,
      isGroupExpense: true,
      groupShareAmount: estimatedShare,
      // Don't include location (expects object) and receiptUrl - they're stored in GroupBudget expense
    });

    await personalExpense.save();

    // Add to GroupBudget
    const expenseData = {
      description,
      amount,
      paidBy: userId,  // Who paid for this expense
      category: category || 'other',
      date: date || new Date(),
      splitType: splitType || 'auto',
      participants: participantUserIds || [],  // Changed from participantUserIds to participants
      customSplits: customSplits || [],
      location,
      notes,
      receiptUrl,
    };

    const expense = groupBudget.addExpense(expenseData, personalExpense._id);
    await groupBudget.save();

    // Update personal expense with accurate share
    const actualSplit = expense.splits.find(s => s.userId.toString() === userId.toString());
    if (actualSplit) {
      personalExpense.groupShareAmount = actualSplit.amount;
      await personalExpense.save();
    }

    successResponse(res, 'Thêm expense thành công', {
      groupBudget,
      expense,
      personalExpense,
    }, 201);
  } catch (error) {
    console.error('❌ Add expense error:', error);
    if (error instanceof NotFoundError || error instanceof ForbiddenError || error instanceof BadRequestError) {
      throw error;
    }
    throw new BadRequestError(error.message);
  }
};

// Record funding contribution
export const recordFunding = async (req, res) => {
  const { id } = req.params;
  const { userId, amount } = req.body;

  const groupBudget = await GroupBudget.findById(id);
  if (!groupBudget) {
    throw new NotFoundError('GroupBudget không tồn tại');
  }

  const member = groupBudget.members.find(m => m.userId.toString() === userId);
  if (!member) {
    throw new BadRequestError('User không phải thành viên');
  }

  member.funded += amount;
  groupBudget.totalFunded += amount;
  await groupBudget.save();

  return successResponse(res, 'Ghi nhận đóng góp thành công', groupBudget);
};

// Record payment/settlement
export const recordPayment = async (req, res) => {
  const { id } = req.params;
  const { fromUserId, toUserId, amount } = req.body;

  const groupBudget = await GroupBudget.findById(id);
  if (!groupBudget) {
    throw new NotFoundError('GroupBudget không tồn tại');
  }

  const fromMember = groupBudget.members.find(m => m.userId.toString() === fromUserId);
  const toMember = groupBudget.members.find(m => m.userId.toString() === toUserId);

  if (!fromMember || !toMember) {
    throw new BadRequestError('User không phải thành viên');
  }

  fromMember.balance += amount;
  toMember.balance -= amount;
  await groupBudget.save();

  return successResponse(res, 'Ghi nhận thanh toán thành công', groupBudget);
};

// Get settlement plan
export const getSettlementPlan = async (req, res) => {
  const { id } = req.params;

  const groupBudget = await GroupBudget.findById(id);
  if (!groupBudget) {
    throw new NotFoundError('GroupBudget không tồn tại');
  }

  const debtors = groupBudget.members.filter(m => m.balance < 0);
  const creditors = groupBudget.members.filter(m => m.balance > 0);

  const settlements = [];
  let i = 0, j = 0;

  while (i < debtors.length && j < creditors.length) {
    const debt = Math.abs(debtors[i].balance);
    const credit = creditors[j].balance;
    const amount = Math.min(debt, credit);

    settlements.push({
      from: debtors[i].userId,
      to: creditors[j].userId,
      amount
    });

    debtors[i].balance += amount;
    creditors[j].balance -= amount;

    if (Math.abs(debtors[i].balance) < 0.01) i++;
    if (Math.abs(creditors[j].balance) < 0.01) j++;
  }

  return successResponse(res, 'Kế hoạch thanh toán', { settlements });
};

// Settle group budget
export const settleGroupBudget = async (req, res) => {
  const { id } = req.params;

  const groupBudget = await GroupBudget.findById(id);
  if (!groupBudget) {
    throw new NotFoundError('GroupBudget không tồn tại');
  }

  groupBudget.isSettled = true;
  groupBudget.isActive = false;
  groupBudget.members.forEach(m => m.balance = 0);
  await groupBudget.save();

  return successResponse(res, 'Đã thanh toán xong GroupBudget', groupBudget);
};

